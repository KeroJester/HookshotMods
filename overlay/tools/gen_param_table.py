#!/usr/bin/env python3
"""Generate overlay/player_param_keys.h: every float in Child Link's PlayerGameParam
(base Player params with the Player_Child overrides applied), for the F2 Param Tuner.
Run from anywhere: python3 overlay/tools/gen_param_table.py"""
import os, sys
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
sys.path.insert(0, ROOT)
from mod_manager import byml, zstd_helper as z

R = os.path.join(ROOT, "romfs")
pack = os.path.join(R, "Pack/Actor/Player_Child.pack.zs")
files = z.unpack_sarc_to_dict(z.decompress_zs(open(pack, "rb").read(), "Player_Child.pack.zs", R))
base = byml.parse_byml(files["Player/PlayerGameParam/Player.game__player__PlayerGameParam.bgyml"])
child = byml.parse_byml(files["Player/PlayerGameParam/Player_Child.game__player__PlayerGameParam.bgyml"])
merged = dict(base); merged.update(child)

# Values from the GoronLink mod's Player_Child pack, if built, so the tuner can tell whether
# the modded values (rather than vanilla) are what the game loaded.
modded = {}
mods = os.path.join(ROOT, "mods")
for d in sorted(os.listdir(mods)):
    mp = os.path.join(mods, d, "romfs/Pack/Actor/Player_Child.pack.zs")
    if d.endswith("-GoronLink") and os.path.exists(mp):
        mf = z.unpack_sarc_to_dict(z.decompress_zs(open(mp, "rb").read(), "Player_Child.pack.zs", R))
        mc = byml.parse_byml(mf["Player/PlayerGameParam/Player_Child.game__player__PlayerGameParam.bgyml"])
        mb = byml.parse_byml(mf["Player/PlayerGameParam/Player.game__player__PlayerGameParam.bgyml"])
        modded = dict(mb); modded.update(mc)
        print("mod values from", d)

rows = []
for k in sorted(merged):
    v = merged[k]
    if type(v) is float:
        mv = modded.get(k, v) if modded else v
        rows.append((k, v, k in child, mv if type(mv) is float else v))
    elif isinstance(v, dict):
        for a in ("X", "Y", "Z"):
            if type(v.get(a)) is float:
                mv = (modded.get(k) or {}).get(a, v[a]) if modded else v[a]
                rows.append((f"{k}.{a}", v[a], k in child, mv if type(mv) is float else v[a]))

out = os.path.join(ROOT, "overlay", "player_param_keys.h")
with open(out, "w") as f:
    f.write("// Generated by overlay/tools/gen_param_table.py - do not edit.\n")
    f.write("// Child Link PlayerGameParam floats (base + Player_Child overrides).\n#pragma once\n")
    f.write("struct ParamKey { const char* name; float child_value; bool child_override; float mod_value; };\n")
    f.write("static const ParamKey kParamKeys[] = {\n")
    for k, v, c, mv in rows:
        f.write(f'    {{"{k}", {v!r}f, {"true" if c else "false"}, {mv!r}f}},\n')
    f.write("};\nstatic const int kParamKeyCount = sizeof(kParamKeys) / sizeof(kParamKeys[0]);\n")
print(f"wrote {out}: {len(rows)} floats ({sum(1 for r in rows if r[2])} child overrides, "
      f"{sum(1 for r in rows if r[3] != r[1])} changed by the mod)")
